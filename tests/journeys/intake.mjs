import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {join} from 'node:path'
import {expect} from '@playwright/test'
export async function intakeJourney({w,browser}) {
 const owner=w.owner,pass=async(p,status=200)=>{const r=await p;assert.equal(r.status,status,JSON.stringify(r.body));return r.body}
 const project=await pass(owner.post('/api/v1/projects',{name:'Creative intake'}))
 const hidden=await pass(owner.post('/api/v1/tasks',{projectId:project.id,title:'synthetic-pegboard-private-work',internalNotes:'synthetic-pegboard-private-note'}))
 const editor=await w.person(['synthetic-pegboard-7001','example.com'].join('@'),'Intake designer')
 await pass(owner.post('/api/v1/grants',{objectType:'project',objectId:project.id,granteeId:editor.id,level:'editor'}))
 const context=await browser.newContext({viewport:{width:1440,height:900}})
 await context.addCookies(owner.cookie.split('; ').map(pair=>({name:pair.slice(0,pair.indexOf('=')),value:pair.slice(pair.indexOf('=')+1),url:w.origin})))
 const page=await context.newPage(),anonymous=await browser.newContext({viewport:{width:1440,height:900}}),publicPage=await anonymous.newPage()
 const proof=async(name,screen=page)=>{
  if(!process.env.PEGBOARD_PROOF_DIR)return
  await mkdir(process.env.PEGBOARD_PROOF_DIR,{recursive:true})
  for(const [width,height]of [[1440,900],[390,844]]){await screen.setViewportSize({width,height});await screen.screenshot({path:join(process.env.PEGBOARD_PROOF_DIR,`intake-${name}-${width}.png`),fullPage:true,mask:[screen.getByLabel('Public form link')]})}
  await screen.setViewportSize({width:1440,height:900})
 }
 const flat=async screen=>assert.ok(await screen.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'intake stays within the viewport')
 try{
  await page.goto(w.origin+`/app/projects/${project.id}/settings`)
  await page.getByRole('link',{name:'Configure intake forms'}).click()
  const form=page.getByRole('form',{name:'Create intake form'})
  await form.getByLabel('Form name',{exact:true}).fill('Creative request')
  await form.getByLabel('Fixed task owner').selectOption(editor.id)
  await form.getByLabel('Fixed task priority').selectOption('high')
  await form.getByLabel('Form name',{exact:true}).focus();await page.keyboard.press('Tab')
  await expect(form.getByLabel('Request title prompt')).toBeFocused()
  await proof('settings');await flat(page)
  await form.getByRole('button',{name:'Create draft'}).click()
  await expect(page.getByRole('heading',{name:'Review exact publication'})).toBeVisible()
  const reviewed=await pass(owner.get(`/api/v1/projects/${project.id}/intake/forms`)),id=reviewed[0].id
  await expect(page.getByText('Owner: Intake designer.',{exact:false})).toBeVisible()
  await proof('publication-review');await flat(page)
  const publish=page.getByRole('form',{name:'Publish intake form'})
  await publish.getByLabel('Audience',{exact:true}).selectOption('public')
  await publish.getByLabel('I approve these exact prompts, task mappings and audience').check()
  await publish.getByRole('button',{name:'Publish reviewed form'}).click()
  await expect(page.getByRole('heading',{name:'Public form published'})).toBeVisible()
  const link=await page.getByLabel('Public form link').inputValue()
  await proof('published-link')
  await publicPage.goto(w.origin+link)
  const request=publicPage.getByRole('form',{name:'Submit request'})
  await expect(request.getByLabel('Request details')).toBeHidden()
  await request.getByLabel('Request title',{exact:true}).fill('Commission a campaign image')
  await request.getByLabel('Request type').selectOption('Design')
  await expect(request.getByLabel('Request details')).toBeVisible()
  await request.getByLabel('Request details').fill('Use <script> as text, not executable markup')
  for(const value of [project.name,editor.name,hidden.id,'synthetic-pegboard-private-work','synthetic-pegboard-private-note'])assert.ok(!(await publicPage.content()).includes(value),'public form excludes internal information')
  await proof('public-form',publicPage);await flat(publicPage)
  await request.getByRole('button',{name:'Submit request'}).click()
  await expect(publicPage.getByRole('heading',{name:'Request received'})).toBeVisible()
  await expect(publicPage.getByRole('status')).toContainText('Receipt')
  await expect(publicPage.getByText('Triage deadline:',{exact:false})).toBeVisible()
  assert.equal(await publicPage.locator('script:not([src])').count(),0,'submitted markup stays inert')
  await proof('public-receipt',publicPage);await flat(publicPage)
  const queue=await pass(owner.get(`/api/v1/projects/${project.id}/intake`)),item=queue.items[0]
  const task=await pass(owner.get('/api/v1/tasks/'+item.taskId))
  assert.equal(task.title,'Commission a campaign image');assert.equal(task.owner.id,editor.id);assert.equal(task.priority,'high')
  assert.equal(task.description,'Request type: Design\nRequest details: Use <script> as text, not executable markup')
  await page.goto(w.origin+`/app/projects/${project.id}/intake`)
  await expect(page.getByRole('link',{name:task.title})).toHaveAttribute('href','/app/tasks/'+task.id)
  await expect(page.getByText('Intake designer · high · waiting',{exact:false})).toBeVisible()
  await proof('triage-waiting');await flat(page)
  await w.sql(`UPDATE peg_intake_submissions SET deadline=1 WHERE id='${item.id}'`)
  await page.reload()
  await expect(page.getByRole('status')).toContainText('Project administrator attention required')
  await proof('triage-overdue');await flat(page)
  await page.getByRole('button',{name:'Mark triaged'}).click()
  await expect(page.locator(`[data-submission="${item.id}"]`)).toContainText('triaged')
  await proof('triage-complete')
  await page.goto(w.origin+'/app/intake/'+id)
  const internal=page.getByRole('form',{name:'Submit request'})
  await internal.getByLabel('Request title',{exact:true}).fill('Internal request')
  await internal.getByLabel('Request type').selectOption('Other')
  await expect(internal.getByLabel('Request details')).toBeHidden()
  await proof('internal-form')
  await internal.getByRole('button',{name:'Submit request'}).click()
  await expect(page.getByRole('heading',{name:'Request received'})).toBeVisible()
  await proof('internal-receipt')
  await pass(owner.post(`/api/v1/intake/forms/${id}/revoke`,{}))
  assert.equal((await publicPage.goto(w.origin+link)).status(),404)
  console.log('PROBE PEG-007 browser: published and internal form pages -> conditional fields, receipt, exact task and visible overdue triage; revoked public page refused')
 }finally{await anonymous.close();await context.close()}
}
