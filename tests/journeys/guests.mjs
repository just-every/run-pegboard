import assert from 'node:assert/strict'
import {expect} from '@playwright/test'
import {mkdir} from 'node:fs/promises'

export async function guestJourney({w,browser,owner,sizes,cookies}) {
  const ok=async promise=>{const r=await promise;assert.equal(r.status,200,JSON.stringify(r.body));return r.body}
  const evidence=process.env.PEGBOARD_SCREENSHOTS
  if(evidence)await mkdir(evidence,{recursive:true})
  let memberCount=1,guestCount=0
  for(const [size,viewport] of sizes){
    memberCount++;guestCount+=2
    const guest=await w.person(`freelancer-${size}${String.fromCharCode(64)}example.test`,'Freelancer','guest')
    const peer=await w.person(`client-peer-${size}${String.fromCharCode(64)}example.test`,'Client colleague','guest')
    const outsider=await w.person(`internal-peer-${size}${String.fromCharCode(64)}example.test`,'Internal colleague')
    const project=await ok(owner.post('/api/v1/projects',{name:`Client project ${size}`,description:'synthetic-pegboard-940'}))
    const manager=await browser.newContext({viewport})
    await manager.addCookies(cookies(owner))
    const managerPage=await manager.newPage()
    const initialShare=async(person,scope='full')=>{
      await managerPage.goto(`${w.origin}/app/projects/${project.id}/settings`)
      const share=managerPage.getByRole('form',{name:'Review initial guest share',exact:true})
      await share.getByLabel('Existing guest',{exact:true}).selectOption(person.id)
      await share.getByLabel('Guest level',{exact:true}).selectOption('editor')
      await share.getByLabel('Guest work scope',{exact:true}).selectOption(scope)
      await share.getByLabel('Access expires at (UTC, optional)',{exact:true}).fill('2030-01-01T12:00')
      await share.getByLabel('Access expires at (UTC, optional)',{exact:true}).focus()
      for(let tab=0;tab<12&&!await share.getByRole('button',{name:'Review guest share',exact:true}).evaluate(el=>el===document.activeElement);tab++)await managerPage.keyboard.press('Tab')
      await expect(share.getByRole('button',{name:'Review guest share',exact:true})).toBeFocused()
      await managerPage.keyboard.press('Enter')
      await expect(managerPage.getByRole('region',{name:'Guest share review'})).toContainText('Excluded from this share')
      return managerPage.getByRole('form',{name:'Confirm guest share',exact:true})
    }
    const emptyConfirmation=await initialShare(guest)
    const emptyReview=managerPage.getByRole('region',{name:'Guest share review'})
    await expect(emptyReview).toContainText('synthetic-pegboard-940')
    assert.equal((await guest.get(`/api/v1/projects/${project.id}`)).status,404)
    if(evidence)await emptyReview.screenshot({path:`${evidence}/empty-project-review-${size}.png`})
    await emptyConfirmation.getByRole('button',{name:'Grant exactly this access',exact:true}).focus()
    await managerPage.keyboard.press('Enter')
    await expect(managerPage.locator('#guest-share-history')).toContainText('approved')
    const emptyGuestContext=await browser.newContext({viewport})
    try {
      await emptyGuestContext.addCookies(cookies(guest))
      const emptyGuestPage=await emptyGuestContext.newPage()
      await emptyGuestPage.goto(`${w.origin}/app/projects/${project.id}`)
      await expect(emptyGuestPage.locator('main')).toContainText('synthetic-pegboard-940')
      assert.ok(await emptyGuestPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
      if(evidence)await emptyGuestPage.screenshot({path:`${evidence}/empty-project-guest-${size}.png`,fullPage:true})
    }finally{await emptyGuestContext.close()}
    const emptyGrant=(await ok(owner.get(`/api/v1/grants?objectType=project&objectId=${project.id}`))).grants.find(g=>g.grantee_id===guest.id)
    await ok(owner.delete(`/api/v1/grants/${emptyGrant.id}`))
    const previewedTask=await ok(owner.post('/api/v1/tasks',{title:'Reviewable client brief',description:'Reviewed client content',projectId:project.id}))
    await ok(owner.post(`/api/v1/tasks/${previewedTask.id}/comments`,{body:'synthetic-pegboard-930',internalOnly:true}))
    let confirm=await initialShare(guest)
    const initialCard=managerPage.locator('#guest-share-review')
    await expect(initialCard).toContainText(`${memberCount} members · ${guestCount} free guests`)
    await expect(initialCard).toContainText('Reviewable client brief')
    await expect(initialCard).not.toContainText('synthetic-pegboard-930')
    assert.equal((await guest.get(`/api/v1/tasks/${previewedTask.id}`)).status,404)
    assert.equal((await ok(owner.get(`/api/v1/grants?objectType=project&objectId=${project.id}`))).grants.length,0)
    if(evidence)await initialCard.screenshot({path:`${evidence}/initial-guest-review-${size}.png`})
    await confirm.getByRole('button',{name:'Cancel guest share',exact:true}).focus()
    await managerPage.keyboard.press('Enter')
    await expect(managerPage.locator('#guest-share-history')).toContainText('cancelled')
    assert.equal((await guest.get(`/api/v1/tasks/${previewedTask.id}`)).status,404)
    confirm=await initialShare(guest)
    await confirm.getByRole('button',{name:'Grant exactly this access',exact:true}).focus()
    await managerPage.keyboard.press('Enter')
    await expect(managerPage.locator('#guest-share-history')).toContainText('approved')
    const decision=(await ok(owner.get(`/api/v1/projects/${project.id}/guest-shares`))).decisions.find(d=>d.status==='approved')
    assert.equal(decision.actorId,owner.id);assert.equal(decision.recipientId,guest.id)
    assert.deepEqual(decision.manifest.taskIds,[previewedTask.id])
    assert.equal((await guest.get(`/api/v1/tasks/${previewedTask.id}`)).status,200)
    await ok(owner.post('/api/v1/grants',{objectType:'project',objectId:project.id,granteeId:peer.id,level:'editor'}))
    const task=await ok(guest.post('/api/v1/tasks',{title:'Client deliverable',projectId:project.id}))
    await managerPage.goto(`${w.origin}/app/tasks/${task.id}`)
    await managerPage.getByRole('form',{name:'Comment',exact:true}).getByLabel('Comment',{exact:true}).fill('Internal margin synthetic-pegboard-907')
    await managerPage.getByLabel('Internal comment',{exact:true}).check()
    await managerPage.getByRole('button',{name:'Comment',exact:true}).click()
    await expect(managerPage.locator('main')).toContainText('Internal margin synthetic-pegboard-907')
    if(evidence)await managerPage.screenshot({path:`${evidence}/member-task-${size}.png`,fullPage:true})
    guestCount++
    const assignee=await w.person(`assigned-${size}${String.fromCharCode(64)}example.test`,'Assigned freelancer','guest')
    const assignedConfirmation=await initialShare(assignee,'assignee')
    await assignedConfirmation.getByRole('button',{name:'Grant exactly this access',exact:true}).focus()
    await managerPage.keyboard.press('Enter')
    await managerPage.waitForURL(url=>url.hash==='#guest-share-history'&&!url.searchParams.has('guestReview'))
    assert.equal((await ok(owner.get(`/api/v1/grants?objectType=project&objectId=${project.id}`))).grants.find(g=>g.grantee_id===assignee.id).scope,'assignee')
    const previewForm=managerPage.getByRole('form',{name:'Preview guest portal'})
    await previewForm.getByLabel('Guest recipient').selectOption(guest.id)
    await previewForm.getByRole('button',{name:'Preview guest portal'}).click()
    const previewCard=managerPage.locator('article').filter({has:managerPage.getByRole('heading',{name:'Guest portal preview',exact:true})})
    await expect(previewCard).toContainText('Client deliverable')
    await expect(previewCard).not.toContainText('Internal margin synthetic-pegboard-907')
    assert.ok(await managerPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    if(evidence)await managerPage.screenshot({path:`${evidence}/guest-preview-${size}.png`,fullPage:true})
    await manager.close()
    const context=await browser.newContext({viewport})
    try {
      await context.addCookies(cookies(guest)); const page=await context.newPage()
      await page.goto(`${w.origin}/app/tasks/${task.id}`)
      assert.ok(!(await page.locator('main').innerText()).includes('Internal margin synthetic-pegboard-907'))
      const form=page.getByRole('form',{name:'Edit task'})
      const select=form.getByLabel('Assigned to')
      await expect(select.locator('option')).toHaveText(['Assigned freelancer','Client colleague','Freelancer','Wes Holloway'])
      assert.equal(await page.locator('main').getByText('Internal colleague',{exact:true}).count(),0)
      await select.selectOption(peer.id);await form.getByRole('button',{name:'Save',exact:true}).click()
      await expect(page.locator('.head')).toContainText('Client colleague')
      assert.equal((await ok(owner.get(`/api/v1/tasks/${task.id}`))).owner.id,peer.id)
      assert.equal((await page.request.patch(`${w.origin}/api/v1/tasks/${task.id}`,{data:{ownerId:outsider.id},headers:{origin:w.origin}})).status(),403)
      await page.getByRole('button',{name:'Mark complete',exact:true}).click()
      await page.getByRole('button',{name:'Reopen',exact:true}).waitFor()
      assert.equal((await ok(owner.get(`/api/v1/tasks/${task.id}`))).status,'done')
      assert.equal(await form.getByLabel('Internal notes (members only)').count(),0)
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
      // Every control on this screen has a visible word label; there are no icon-only actions.
      for(const control of await page.locator('button,a').all()) if(await control.isVisible()) assert.ok((await control.innerText()).trim(),`unlabelled control at ${size}`)
      if(evidence)await page.screenshot({path:`${evidence}/guest-task-${size}.png`,fullPage:true})
      const grant=(await ok(owner.get(`/api/v1/grants?objectType=project&objectId=${project.id}`))).grants.find(g=>g.grantee_id===guest.id)
      await ok(owner.delete(`/api/v1/grants/${grant.id}`))
      assert.equal((await page.goto(`${w.origin}/app/tasks/${task.id}`)).status(),404)
      assert.ok(!(await page.locator('main').innerText()).includes('Client deliverable'))
      const retained=(await ok(owner.get(`/api/v1/projects/${project.id}/guest-shares`))).decisions.find(d=>d.id===decision.id)
      assert.deepEqual(retained,decision)
      assert.equal((await owner.post(`/api/v1/projects/${project.id}/guest-shares/${decision.id}/decision`,{decision:'approve',fingerprint:decision.fingerprint})).status,409)
    }finally{await context.close()}
  }
  console.log('Scoped guest task screens passed at 1440 and 390')
}
