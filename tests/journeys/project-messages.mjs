import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {join} from 'node:path'
import {expect} from '@playwright/test'
import {messageFixture,pass,thread,notices,messagePath,grant} from '../scenarios/project-messages.mjs'

/** One keyboard workflow at desktop width; the same changed screens are inspected at phone width. */
export async function projectMessagesJourney({w,browser}){
 const f=await messageFixture(w), contexts=[]
 const open=async client=>{const context=await browser.newContext({viewport:{width:1440,height:900}});contexts.push(context);await context.addCookies(client.cookie.split('; ').map(pair=>({name:pair.slice(0,pair.indexOf('=')),value:pair.slice(pair.indexOf('=')+1),url:w.origin})));return context.newPage()}
 const capture=async(name,page)=>{
  if(!process.env.PEGBOARD_PROOF_DIR)return
  await mkdir(process.env.PEGBOARD_PROOF_DIR,{recursive:true})
  for(const [width,height]of [[1440,900],[390,844]]){
   await page.setViewportSize({width,height})
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'message screen fits '+width)
   await page.screenshot({path:join(process.env.PEGBOARD_PROOF_DIR,'project-messages-'+name+'-'+width+'.png'),fullPage:true})
  }
  await page.setViewportSize({width:1440,height:900})
 }
 const press=async(page,locator)=>{await locator.focus();await Promise.all([page.waitForNavigation({waitUntil:'domcontentloaded'}),page.keyboard.press('Enter')])}
 try{
  const page=await open(f.owner),reader=await open(f.reader),observer=await open(f.viewer)
  await page.goto(w.origin+'/app/projects/'+f.project.id)
  await press(page,page.getByRole('link',{name:'Messages',exact:true}))
  await expect(page.getByRole('heading',{name:'Project Messages',exact:true})).toBeVisible()
  await capture('entry',page)
  await press(page,page.getByRole('link',{name:'Compose announcement',exact:true}))
  const compose=page.getByRole('form',{name:'Save announcement draft'})
  await compose.getByLabel('Subject',{exact:true}).fill('Autumn launch decision brief')
  await compose.getByLabel('Announcement body').fill('The launch materials are ready for review.\nPlease reply with any changes before our planning session.')
  await compose.getByLabel('Reviewed audience').selectOption([f.reader.id,f.viewer.id])
  await compose.getByLabel('Work links').selectOption(f.task.id)
  await compose.getByLabel('Subject',{exact:true}).focus();await page.keyboard.press('Tab');await expect(compose.getByLabel('Announcement body')).toBeFocused()
  await capture('compose',page)
  await press(page,compose.getByRole('button',{name:'Save draft',exact:true}))
  await page.waitForURL(/\/app\/message-drafts\/message_/)
  const draftId=new URL(page.url()).pathname.split('/').at(-1)
  const saved=await pass(f.owner.get('/api/v1/message-drafts/'+draftId))
  assert.equal(saved.subject,'Autumn launch decision brief');assert.deepEqual(saved.recipients.sort(),[f.reader.id,f.viewer.id].sort())
  assert.equal((await notices(f.reader)).notices.length,0)
  await press(page,page.getByRole('button',{name:'Review exact announcement',exact:true}))
  await expect(page.getByRole('heading',{name:'Review exact announcement',exact:true})).toBeVisible()
  await expect(page.locator('[data-recipient-id="'+f.reader.id+'"]')).toContainText('Campaign reviewer')
  await expect(page.locator('main')).toContainText(saved.body)
  await capture('review',page)
  const publish=page.getByRole('form',{name:'Publish exact announcement'})
  await publish.getByRole('checkbox').focus();await page.keyboard.press('Space')
  await press(page,publish.getByRole('button',{name:'Publish announcement',exact:true}))
  await page.waitForURL(/\/app\/messages\/publication_/)
  const publication=new URL(page.url()).pathname.split('/').at(-1)
  const view=await thread(f.owner,publication)
  assert.equal(view.publications[0].draft_id,draftId)
  assert.equal(view.publications[0].body,saved.body)
  await capture('published',page)
  await reader.goto(w.origin+'/app/inbox')
  const receipt=(await notices(f.reader)).notices.find(n=>n.publicationId===publication)
  const notice=reader.locator('[data-message-notice-id="'+receipt.id+'"]')
  await expect(notice).toHaveCount(1);await expect(notice).toHaveAttribute('data-event-id',publication);await expect(notice).toHaveAttribute('data-recipient-id',f.reader.id)
  await capture('recipient-inbox',reader)
  await press(reader,notice.getByRole('link',{name:saved.subject,exact:true}))
  const reply=reader.getByRole('form',{name:'Reply to announcement'})
  await reply.getByLabel('Reply body').fill('I reviewed the materials. Please correct the meeting date.')
  await press(reader,reply.getByRole('button',{name:'Post reply',exact:true}))
  const after=await thread(f.reader,publication),comment=after.comments[0]
  await expect(reader.locator('[data-comment-id="'+comment.id+'"]')).toContainText(comment.body)
  assert.equal(comment.publication_id,publication);assert.equal(comment.author_id,f.reader.id)
  const edit=reader.getByRole('form',{name:'Revise reply '+comment.id})
  await edit.getByLabel('Revised reply').fill('Reviewed. Please correct the planning date.')
  await press(reader,edit.getByRole('button',{name:'Save reply revision'}))
  const edited=await thread(f.reader,publication)
  assert.equal(edited.comments[0].revision,2);assert.equal(edited.history.length,2)
  await capture('thread-revision',reader)
  await page.reload()
  await press(page,page.getByRole('link',{name:'Write a correction',exact:true}))
  await page.getByLabel('Announcement body').fill('Correction: the planning session is tomorrow. The original announcement remains in history.')
  await press(page,page.getByRole('button',{name:'Save draft',exact:true}))
  await press(page,page.getByRole('button',{name:'Review exact announcement',exact:true}))
  await page.getByRole('checkbox').check()
  await press(page,page.getByRole('button',{name:'Publish announcement',exact:true}))
  await expect(page.locator('[data-publication-id]')).toHaveCount(2)
  const corrected=await thread(f.reader,publication)
  assert.equal(corrected.publications.length,2);assert.equal(corrected.publications.find(p=>p.id===publication).body,saved.body)
  await capture('correction',page)
  await observer.goto(w.origin+'/app/messages/'+publication)
  const pref=observer.getByRole('form',{name:'Thread preferences'})
  await pref.getByLabel('Thread notices').selectOption('true')
  await press(observer,pref.getByRole('button',{name:'Save thread preferences'}))
  assert.equal((await thread(f.viewer,publication)).preferences.muted,true)
  await capture('muted-thread',observer)
  await observer.goto(w.origin+'/app/inbox');await expect(observer.locator('[data-message-notice-id]')).toHaveCount(0)
  await capture('muted-inbox',observer)
  // A stale reviewed form cannot publish after its linked work changes.
  await page.goto(w.origin+'/app/projects/'+f.project.id+'/messages/new')
  await page.getByLabel('Subject',{exact:true}).fill('Stale review must refuse')
  await page.getByLabel('Announcement body').fill('Do not publish this after the linked work changes.')
  await page.getByLabel('Reviewed audience').selectOption(f.reader.id)
  await page.getByLabel('Work links').selectOption(f.task.id)
  await press(page,page.getByRole('button',{name:'Save draft',exact:true}))
  await press(page,page.getByRole('button',{name:'Review exact announcement',exact:true}))
  await pass(f.owner.patch('/api/v1/tasks/'+f.task.id,{description:'Later human source edit'}))
  await page.getByRole('checkbox').check()
  const refused=page.waitForResponse(r=>r.url().includes('/publish')&&r.request().method()==='POST')
  await press(page,page.getByRole('button',{name:'Publish announcement',exact:true}))
  assert.equal((await refused).status(),409)
  await capture('stale-refused',page)
  const pinned=await thread(f.reader,publication)
  await pass(f.owner.post('/api/v1/grants/'+f.readGrant.id+'/revoke',{}))
  const response=await reader.goto(w.origin+'/app/messages/'+publication)
  assert.equal(response.status(),404)
  await expect(reader.locator('main')).not.toContainText(saved.body)
  await capture('revoked-thread',reader)
  await reader.goto(w.origin+'/app/inbox');await expect(reader.locator('[data-message-notice-id]')).toHaveCount(0)
  await pass(f.reader.post(messagePath(publication)+'/replies',{token:pinned.token,key:'synthetic-pegboard-1430',body:'Revoked browser tab'}),404)
  await grant(f.owner,f.project,f.reader)
  assert.equal((await notices(f.reader)).notices.length,0)
  console.log('PROBE PEG-010 browser: project entry, keyboard compose and exact review -> immutable publication and matching recipient Inbox IDs; thread reply and edit, correction and mute -> API-reconciled records; stale publication and revoked tab -> refused with no content. Changed screens inspected at 1440 and 390.')
 }finally{for(const c of contexts)await c.close()}
}
