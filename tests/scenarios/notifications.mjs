import assert from 'node:assert/strict'
const ok=async(p,status=200)=>{const r=await p;assert.equal(r.status,status,JSON.stringify(r.body));return r.body}
const inbox=client=>ok(client.get('/api/v1/notices'))
const noticesFor=(view,task)=>view.items.filter(n=>n.taskId===task.id)
export async function notificationScenario(w) {
 const owner=w.owner
 const member=await w.person(['synthetic-pegboard-9001','example.com'].join('@'),'Notice member')
 const follower=await w.person(['synthetic-pegboard-9002','example.com'].join('@'),'Same name')
 const other=await w.person(['synthetic-pegboard-9003','example.com'].join('@'),'Same name')
 const outsider=await w.person(['synthetic-pegboard-9004','example.com'].join('@'),'Notice outsider')
 const guest=await w.person(['synthetic-pegboard-9005','example.com'].join('@'),'Notice guest','guest')
 const project=await ok(owner.post('/api/v1/projects',{name:'Member notices',privacy:'private'}))
 for(const person of [member,follower,other])await ok(owner.post('/api/v1/grants',{objectType:'project',objectId:project.id,granteeId:person.id,level:'editor'}))
 await ok(owner.post('/api/v1/grants',{objectType:'project',objectId:project.id,granteeId:guest.id,level:'commenter'}))
 await ok(member.post('/api/v1/notices/policy',{enabled:true}),403)
 await ok(guest.get('/api/v1/notices'),403)
 const before=await ok(owner.post('/api/v1/tasks',{title:'No policy backfill',projectId:project.id,ownerId:member.id}))
 assert.deepEqual((await inbox(member)).items,[],'default denies notice delivery')
 await ok(owner.post('/api/v1/notices/policy',{enabled:true}))
 assert.deepEqual((await inbox(member)).items,[],'approving does not replay old work')
 const task=await ok(owner.post('/api/v1/tasks',{title:'Assigned campaign',projectId:project.id,ownerId:member.id,priority:'urgent'}))
 let view=await inbox(member),assigned=noticesFor(view,task)
 assert.equal(assigned.length,1);assert.equal(assigned[0].recipientId,member.id);assert.equal(assigned[0].reason,'assignment')
 assert.equal(noticesFor(await inbox(member),before).length,0)
 await ok(member.post(`/api/v1/notices/${assigned[0].id}/state`,{read:true}))
 assert.equal(noticesFor(await inbox(member),task)[0].read,true)
 await ok(other.post(`/api/v1/notices/${assigned[0].id}/state`,{read:true}),404)
 await ok(outsider.post(`/api/v1/tasks/${task.id}/notice-preferences`,{following:true}),404)
 await ok(outsider.get(`/api/v1/tasks/${task.id}`),404)
 for(const person of [follower,other])await ok(person.post(`/api/v1/tasks/${task.id}/notice-preferences`,{following:true}))
 await ok(other.post(`/api/v1/tasks/${task.id}/notice-preferences`,{muted:true}))
 await ok(owner.patch(`/api/v1/tasks/${task.id}`,{collaborators:[follower.id,other.id]}))
 const command={body:'Review the composition',mentionId:follower.id,operationId:'synthetic-pegboard-9006'}
 const responses=await Promise.all([owner.post(`/api/v1/tasks/${task.id}/comments`,command),owner.post(`/api/v1/tasks/${task.id}/comments`,command)])
 for(const r of responses)assert.equal(r.status,200,JSON.stringify(r.body))
 assert.equal(responses[0].body.id,responses[1].body.id)
 const commentId=responses[0].body.id
 view=await inbox(follower)
 assert.deepEqual(noticesFor(view,task).map(n=>[n.commentId,n.recipientId,n.reason]),[[commentId,follower.id,'mention']])
 assert.equal(noticesFor(await inbox(other),task).length,0,'muted member with the same display name receives nothing')
 await ok(other.post(`/api/v1/tasks/${task.id}/notice-preferences`,{muted:false}))
 assert.equal(noticesFor(await inbox(other),task).length,0,'unmuting cannot backfill a notice from the muted stream')
 assert.equal(noticesFor(await inbox(member),task).filter(n=>n.kind==='comment').length,1,'current owner receives comment notice')
 const mutedTask=await ok(owner.post('/api/v1/tasks',{title:'Muted mention stream',projectId:project.id,ownerId:member.id}))
 await ok(owner.patch(`/api/v1/tasks/${mutedTask.id}`,{collaborators:[other.id]}))
 await ok(other.post(`/api/v1/tasks/${mutedTask.id}/notice-preferences`,{muted:true}))
 await ok(owner.post(`/api/v1/tasks/${mutedTask.id}/comments`,{body:'Mention a muted identity',mentionId:other.id}))
 assert.equal(noticesFor(await inbox(other),mutedTask).length,0,'a mention cannot bypass stream mute')
 await ok(other.post(`/api/v1/tasks/${mutedTask.id}/notice-preferences`,{muted:false}))
 assert.equal(noticesFor(await inbox(other),mutedTask).length,0)
 await ok(owner.post(`/api/v1/tasks/${task.id}/comments`,{...command,body:'Changed capture'}),400)
 await ok(owner.post(`/api/v1/tasks/${task.id}/comments`,{body:'Forbidden identity',mentionId:outsider.id}),400)
 await ok(owner.post(`/api/v1/tasks/${task.id}/comments`,{body:'Forbidden identity',mentionId:guest.id}),400)
 let taskView=await ok(owner.get(`/api/v1/tasks/${task.id}`))
 assert.equal(taskView.comments.filter(c=>c.id===commentId).length,1)
 assert.equal(taskView.history.filter(h=>h.kind==='comment.added').length,1)
 await w.restart()
 assert.equal((await ok(owner.post(`/api/v1/tasks/${task.id}/comments`,command))).id,commentId)
 assert.deepEqual(noticesFor(await inbox(follower),task).map(n=>n.id),view.items.map(n=>n.id))
 console.log('PROBE PEG-009 identity and replay: native comment POST with same-name members and concurrent operation key -> one comment, one identity-bound mention, muted member absent after restart')
 // DND holds an event without consuming it, then release delivers once.
 await ok(member.post('/api/v1/notices/preferences',{dndUntil:4102444800000}))
 const held=await ok(owner.post('/api/v1/tasks',{title:'DND held assignment',projectId:project.id,ownerId:member.id}))
 assert.equal(noticesFor(await inbox(member),held).length,0)
 await ok(member.post('/api/v1/notices/preferences',{dndUntil:1}))
 const concurrent=await Promise.all([inbox(member),inbox(member),inbox(member)])
 const released=noticesFor(concurrent[0],held)
 for(const result of concurrent)assert.equal(noticesFor(result,held).length,1)
 assert.equal(released.length,1)
 assert.deepEqual(noticesFor(await inbox(member),held).map(n=>n.id),released.map(n=>n.id))
 const mutedQueued=await ok(owner.post('/api/v1/tasks',{title:'Cancelled queued notice',projectId:project.id,ownerId:member.id}))
 await ok(member.post(`/api/v1/tasks/${mutedQueued.id}/notice-preferences`,{muted:true}))
 await ok(member.post(`/api/v1/tasks/${mutedQueued.id}/notice-preferences`,{muted:false}))
 assert.equal(noticesFor(await inbox(member),mutedQueued).length,0,'a briefly muted queued notice cannot revive')
 // Reassignment before dispatch chooses only the last current assignee.
 const reassigned=await ok(owner.post('/api/v1/tasks',{title:'Current recipient only',projectId:project.id,ownerId:member.id}))
 await ok(owner.patch(`/api/v1/tasks/${reassigned.id}`,{ownerId:follower.id}))
 assert.equal(noticesFor(await inbox(member),reassigned).length,0)
 assert.equal(noticesFor(await inbox(follower),reassigned).length,1)
 console.log('PROBE PEG-009 dispatch: native assignment plus DND release and reassignment -> one delayed delivery and only the current assignee')
 // A follower who no longer follows gets neither new comments nor old follower-only reads.
 const followed=await ok(owner.post('/api/v1/tasks',{title:'Followed work',projectId:project.id,ownerId:member.id}))
 await ok(follower.post(`/api/v1/tasks/${followed.id}/notice-preferences`,{following:true}))
 await ok(owner.post(`/api/v1/tasks/${followed.id}/comments`,{body:'Follower sees this'}))
 assert.equal(noticesFor(await inbox(follower),followed).length,1)
 await ok(follower.post(`/api/v1/tasks/${followed.id}/notice-preferences`,{following:false}))
 await ok(owner.post(`/api/v1/tasks/${followed.id}/comments`,{body:'Unfollowed stream'}))
 assert.equal(noticesFor(await inbox(follower),followed).length,0)
 // A comment in another home never contributes a notice or a count.
 const hidden=await ok(owner.post('/api/v1/projects',{name:'Hidden comment home',privacy:'private'}))
 await ok(owner.post(`/api/v1/tasks/${task.id}/projects`,{projectId:hidden.id}))
 await ok(owner.post('/api/v1/grants',{objectType:'project',objectId:hidden.id,granteeId:outsider.id,level:'editor'}))
 const hiddenComment=await ok(outsider.post(`/api/v1/tasks/${task.id}/comments`,{body:'Hidden-home comment'}))
 const safe=await inbox(follower)
 assert.equal(safe.items.some(n=>n.commentId===hiddenComment.id),false)
 assert.equal(safe.unread,safe.items.filter(n=>!n.read).length)
 assert.equal((await follower.get('/app/inbox')).body.includes(hiddenComment.id),false)
 console.log('PROBE PEG-009 access: hidden comment home and unfollow through native reads -> no hidden event, content or count; following grants no private access')
 // Snoozing an approval only affects the recipient notice, not its decision or work.
 const approval=await ok(owner.post('/api/v1/tasks',{title:'Approve campaign',kind:'approval',projectId:project.id,ownerId:member.id}))
 const approvalNotice=noticesFor(await inbox(owner),approval).find(n=>n.kind==='approval')
 assert.ok(approvalNotice)
 const decisionBefore=await ok(owner.get(`/api/v1/tasks/${approval.id}/decision-preview`))
 await ok(owner.post(`/api/v1/notices/${approvalNotice.id}/state`,{snoozedUntil:4102444800000}))
 view=await inbox(owner)
 assert.equal(noticesFor(view,approval).length,0)
 assert.equal(view.snoozed.find(n=>n.id===approvalNotice.id).href,`/app/tasks/${approval.id}`)
 assert.equal((await ok(owner.get(`/api/v1/tasks/${approval.id}/decision-preview`))).token,decisionBefore.token)
 await w.restart()
 assert.equal((await inbox(owner)).snoozed.filter(n=>n.id===approvalNotice.id).length,1)
 await w.sql(`UPDATE peg_notice_targets SET snoozed_until=1 WHERE event_id='${approvalNotice.id}'`)
 assert.equal(noticesFor(await inbox(owner),approval).filter(n=>n.id===approvalNotice.id).length,1)
 assert.equal((await ok(owner.get(`/api/v1/tasks/${approval.id}/decision-preview`))).token,decisionBefore.token)
 await ok(owner.post(`/api/v1/tasks/${approval.id}/decision`,{revision:decisionBefore.token,action:'approve',reason:'Reviewed after snooze'}))
 assert.equal((await ok(owner.get(`/api/v1/tasks/${approval.id}`))).status,'done')
 assert.equal(noticesFor(await inbox(owner),approval).length,0,'a decided approval does not return as an actionable request')
 console.log('PROBE PEG-009 snooze: approval notice state POST, restart and elapsed snooze -> same actionable approval and unchanged decision token')
 // DND must not hide or prevent releasing a previously delivered approval.
 const dndApproval=await ok(owner.post('/api/v1/tasks',{title:'Snoozed across DND',kind:'approval',projectId:project.id,ownerId:member.id}))
 const dndNotice=noticesFor(await inbox(owner),dndApproval).find(n=>n.kind==='approval')
 const beforeDnd=await ok(owner.get(`/api/v1/tasks/${dndApproval.id}/decision-preview`))
 await ok(owner.post(`/api/v1/notices/${dndNotice.id}/state`,{snoozedUntil:4102444800000}))
 await ok(owner.post('/api/v1/notices/preferences',{dndUntil:4102444800000}))
 const quietApproval=await ok(owner.post('/api/v1/tasks',{title:'Queued during approval snooze',kind:'approval',projectId:project.id,ownerId:member.id}))
 const duringDnd=await ok(owner.get(`/api/v1/tasks/${dndApproval.id}/decision-preview`))
 assert.equal(duringDnd.state,'pending')
 assert.deepEqual(duringDnd.decisions,beforeDnd.decisions)
 view=await inbox(owner)
 assert.equal(view.deferred,true)
 assert.equal(view.snoozed.filter(n=>n.id===dndNotice.id).length,1,'DND keeps the delivered snoozed approval actionable')
 assert.equal(view.snoozed.find(n=>n.id===dndNotice.id).href,`/app/tasks/${dndApproval.id}`)
 assert.equal(noticesFor(view,quietApproval).length,0,'DND still defers a new approval notice')
 await w.restart()
 assert.equal((await inbox(owner)).snoozed.filter(n=>n.id===dndNotice.id).length,1)
 await ok(owner.post(`/api/v1/notices/${dndNotice.id}/state`,{snoozedUntil:null}))
 assert.equal(noticesFor(await inbox(owner),dndApproval).filter(n=>n.id===dndNotice.id).length,1,'release during DND returns the same delivered notice')
 assert.equal(noticesFor(await inbox(owner),quietApproval).length,0)
 const afterRelease=await ok(owner.get(`/api/v1/tasks/${dndApproval.id}/decision-preview`))
 assert.equal(afterRelease.token,duringDnd.token)
 assert.equal(afterRelease.state,'pending')
 assert.deepEqual(afterRelease.decisions,beforeDnd.decisions)
 await ok(owner.post(`/api/v1/tasks/${dndApproval.id}/decision`,{revision:afterRelease.token,action:'approve',reason:'Reviewed during DND'}))
 assert.equal((await ok(owner.get(`/api/v1/tasks/${dndApproval.id}`))).status,'done')
 assert.equal(noticesFor(await inbox(owner),dndApproval).length,0)
 await ok(owner.post('/api/v1/notices/preferences',{dndUntil:1}))
 assert.equal(noticesFor(await inbox(owner),quietApproval).length,1,'the queued approval delivers after DND ends')
 console.log('PROBE PEG-009 BLOCKING-A: snooze approval, enable DND, restart and release through native notice POST -> same actionable notice, release 200, unchanged pending decision, new approval deferred until DND ends')
 // Revoked and deactivated recipients cannot read previously delivered events.
 const grants=await ok(owner.get(`/api/v1/grants?objectType=project&objectId=${project.id}`))
 const memberGrant=grants.grants?.find(g=>g.granteeId===follower.id||g.grantee_id===follower.id)
 assert.ok(memberGrant);await ok(owner.post(`/api/v1/grants/${memberGrant.id}/revoke`,{}))
 assert.equal(noticesFor(await inbox(follower),reassigned).length,0)
 await ok(owner.post(`/api/v1/workspaces/ws_main/people/${member.id}/account`,{status:'inactive'}))
 assert.ok([401,403].includes((await member.get('/api/v1/notices')).status))
 await ok(owner.post(`/api/v1/workspaces/ws_main/people/${member.id}/account`,{status:'active'}))
 const renewed=await w.signIn(member.email,member.name,member.id)
 assert.equal((await inbox(renewed)).items.length,0,'new sign-in cannot revive events bound to an earlier identity version')
 await ok(owner.post('/api/v1/notices/policy',{enabled:false}))
 assert.equal((await inbox(owner)).items.length,0)
 await ok(owner.post('/api/v1/notices/policy',{enabled:true}))
 assert.equal((await inbox(owner)).items.length,0,'reapproving policy does not resurrect old events')
 console.log('PROBE PEG-009 lifecycle: revoke grant, disable reader and renew policy -> old delivery access refused and old events remain inactive')
 return {project,task,owner,member,follower,other,approval}
}
