import assert from 'node:assert/strict'

const pass=async promise=>{const response=await promise;assert.equal(response.status,200,JSON.stringify(response.body));return response.body}
const read=(client,id)=>pass(client.get(`/api/v1/tasks/${id}`))
const dates=task=>[task.startDate,task.dueDate]
const project=async(client,n)=>({...await pass(client.post('/api/v1/projects',{name:`synthetic-pegboard-${n}`})),name:`synthetic-pegboard-${n}`})
const work=async(client,projectId,n,extra={})=>({...await pass(client.post('/api/v1/tasks',{projectId,title:`synthetic-pegboard-${n}`,startDate:'2026-06-29',dueDate:'2026-07-01',...extra})),title:`synthetic-pegboard-${n}`})
const grant=(root,projectId,person)=>pass(root.post('/api/v1/grants',{objectType:'project',objectId:projectId,granteeId:person.id,level:'editor'}))
async function activate(client,projectId,n,extra={}){
 const bundle=await pass(client.post('/api/v1/workflow-bundles',{name:`synthetic-pegboard-${n}`})),path=`/api/v1/workflow-bundles/${bundle.id}`
 await pass(client.post(path+'/versions',{version:1,key:'schedule',kind:'rule',name:`synthetic-pegboard-${n+1}`,priority:'high',dueDate:'2026-07-02',...extra}))
 const preview=await pass(client.post(path+'/preview',{projectIds:[projectId]}))
 await pass(client.post(path+'/adopt',{projectIds:[projectId],keys:['schedule'],revision:preview.token}))
 return {path,preview}
}

export function registerScheduleRuleTests({test,api}){
 test('applies a reviewed cross-project rule cascade once with assignment, work action, attribution and coherent undo',async()=>{
  const {root,peer,worker}=api(),source=await project(root,9401),downstream=await project(root,9402)
  await Promise.all([grant(root,source.id,peer),grant(root,downstream.id,peer)])
  const successor=await work(root,downstream.id,9403,{startDate:'2026-07-02',dueDate:'2026-07-02'})
  const rule=await activate(root,source.id,9404,{ownerId:peer.id,dependencyProjectIds:[downstream.id],actions:[{kind:'comment',value:'synthetic-pegboard-9406'}]})
  assert.deepEqual(rule.preview.projects[0].rows[0].scheduleScope.map(p=>p.id).sort(),[source.id,downstream.id].sort())
  const predecessor=await work(root,source.id,9407)
  await pass(root.post('/api/v1/dependencies',{predecessor:predecessor.id,successor:successor.id,type:'fs'}))
  await worker.restart()
  assert.equal((await pass(root.post(rule.path+'/jobs/process',{}))).applied,1)
  assert.equal((await pass(root.post(rule.path+'/jobs/process',{}))).applied,0)
  const first=await read(root,predecessor.id),second=await read(root,successor.id)
  assert.deepEqual(dates(first),['2026-06-29','2026-07-02']);assert.deepEqual(dates(second),['2026-07-06','2026-07-06'])
  assert.equal(first.owner.id,peer.id);assert.equal(first.priority,'high');assert.equal(first.comments.length,1)
  const applied=second.history.filter(h=>h.kind==='bundle.rule_applied');assert.equal(applied.length,1);assert.equal(applied[0].actor,root.name)
  const job=(await pass(root.get(rule.path))).jobs.find(j=>j.task_id===predecessor.id)
  assert.equal(job.status,'applied');assert.equal(job.activating_admin,root.id)
  const undoPath=`/api/v1/recovery/bulk/${job.operation_id}`,undo=await pass(root.get(undoPath+'/undo-preview'))
  assert.equal(undo.conflicts.length,0);assert.ok(undo.restored.some(e=>e.taskId===successor.id));assert.equal(undo.origin.activating_admin,root.id)
  await pass(root.post(undoPath+'/undo',{token:undo.token}))
  const restored=await read(root,predecessor.id)
  assert.deepEqual(dates(restored),['2026-06-29','2026-07-01']);assert.equal(restored.owner.id,root.id);assert.equal(restored.comments.length,0)
  assert.deepEqual(dates(await read(root,successor.id)),['2026-07-02','2026-07-02'])
  await worker.restart();assert.equal((await pass(root.post(rule.path+'/jobs/process',{}))).applied,0)
  const later=await work(root,downstream.id,9408,{startDate:'2026-07-02',dueDate:'2026-07-02'}),next=await work(root,source.id,9409)
  await pass(root.post('/api/v1/dependencies',{predecessor:next.id,successor:later.id,type:'fs'}));await pass(root.post(rule.path+'/jobs/process',{}))
  const moves=[{taskId:later.id,start:'2026-07-07',due:'2026-07-07'}],humanPlan=await pass(peer.post('/api/v1/schedule/preview',{moves}))
  await pass(peer.post('/api/v1/schedule/apply',{moves,revision:humanPlan.stamp}))
  const nextJob=(await pass(root.get(rule.path))).jobs.find(j=>j.task_id===next.id),nextUndoPath=`/api/v1/recovery/bulk/${nextJob.operation_id}`
  const preserved=await pass(root.get(nextUndoPath+'/undo-preview'));assert.ok(preserved.conflicts.some(c=>c.taskId===later.id&&c.reason==='later_field_value'))
  await pass(root.post(nextUndoPath+'/undo',{token:preserved.token}))
  assert.deepEqual(dates(await read(root,later.id)),['2026-07-07','2026-07-07']);assert.deepEqual(dates(await read(root,next.id)),['2026-06-29','2026-07-01'])
 })
 test('holds an inseparable hidden cascade without effects or disclosure and refuses a revoked activating Admin',async()=>{
  const {root,peer,guest,worker}=api(),source=await project(root,9411),privateProject=await project(peer,9412)
  await grant(root,source.id,peer)
  const hidden=await work(peer,privateProject.id,9413,{startDate:'2026-07-02',dueDate:'2026-07-02'})
  const rule=await activate(root,source.id,9414,{ownerId:peer.id,actions:[{kind:'comment',value:'synthetic-pegboard-9416'},{kind:'subtask',value:'synthetic-pegboard-9417'}]})
  const predecessor=await work(root,source.id,9418)
  await pass(peer.post('/api/v1/dependencies',{predecessor:predecessor.id,successor:hidden.id,type:'fs'}))
  const before=await read(root,predecessor.id)
  assert.equal((await pass(root.post(rule.path+'/jobs/process',{}))).pending,1)
  const after=await read(root,predecessor.id)
  assert.deepEqual(dates(after),dates(before));assert.equal(after.owner.id,before.owner.id);assert.equal(after.priority,before.priority)
  assert.equal(after.comments.length,before.comments.length);assert.equal(after.subtasks.length,before.subtasks.length)
  assert.deepEqual(dates(await read(peer,hidden.id)),['2026-07-02','2026-07-02'])
  let view=await pass(root.get(rule.path)),job=view.jobs.find(j=>j.task_id===predecessor.id)
  assert.equal(job.status,'pending');assert.equal(job.operation_id,null);assert.equal(job.outcome_reason,'rule_schedule_pending')
  for(const value of [hidden.id,hidden.title,privateProject.id,privateProject.name])assert.ok(!JSON.stringify(view).includes(value),'pending run retains no hidden task or project data')
  await worker.restart();await pass(root.post(rule.path+'/jobs/process',{}));view=await pass(root.get(rule.path));assert.equal(view.jobs.find(j=>j.id===job.id).status,'pending')
  const reviewPath=rule.path+`/jobs/${job.id}/schedule-preview`,approvePath=rule.path+`/jobs/${job.id}/schedule-approve`
  assert.equal((await peer.get(reviewPath)).status,403)
  const oldReview=await pass(root.get(reviewPath))
  for(const client of [peer,guest])assert.equal((await client.post(approvePath,{token:oldReview.token})).status,403)
  assert.deepEqual(oldReview.plan.shifts.map(row=>row.id).sort(),[predecessor.id,hidden.id].sort())
  assert.deepEqual(oldReview.actions.map(row=>row.kind),['comment','subtask'])
  await pass(peer.patch(`/api/v1/tasks/${hidden.id}`,{title:'synthetic-pegboard-9419'}))
  const beforeRefusal=[await read(root,predecessor.id),await read(peer,hidden.id)]
  assert.equal((await root.post(approvePath,{token:oldReview.token})).status,409)
  assert.deepEqual([await read(root,predecessor.id),await read(peer,hidden.id)],beforeRefusal)
  const reviewed=await pass(root.get(reviewPath)),approved=await pass(root.post(approvePath,{token:reviewed.token}))
  assert.equal(approved.status,'applied')
  const applied=await read(root,predecessor.id)
  assert.deepEqual(dates(applied),['2026-06-29','2026-07-02']);assert.equal(applied.owner.id,peer.id);assert.equal(applied.priority,'high')
  assert.equal(applied.comments.length,before.comments.length+1);assert.equal(applied.subtasks.length,before.subtasks.length+1)
  assert.deepEqual(dates(await read(peer,hidden.id)),['2026-07-06','2026-07-06'])
  assert.equal(applied.history.filter(row=>row.kind==='bundle.rule_approved').length,1)
  assert.equal(applied.history.find(row=>row.kind==='bundle.rule_approved').actor,root.name)
  assert.equal((await root.post(approvePath,{token:reviewed.token})).status,409)
  assert.deepEqual(await read(root,predecessor.id),applied)
  const approvedView=await pass(root.get(rule.path)),approvedJob=approvedView.jobs.find(row=>row.id===job.id)
  assert.equal(approvedJob.status,'applied');assert.equal(approvedJob.operation_id,approved.operationId)
  assert.deepEqual(approvedView.items.find(row=>row.item_key==='schedule').config.dependencyProjectIds??[],[],'one exact decision never widens standing activation')
  let activator=await worker.person('schedule-rule-activator@example.com','Synthetic Schedule Admin')
  await pass(root.post(`/api/v1/workspaces/ws_main/people/${activator.id}/account`,{role:'admin'}))
  activator=await worker.signIn('schedule-rule-activator@example.com','Synthetic Schedule Admin',activator.id)
  const other=await project(root,9421),revokedRule=await activate(activator,other.id,9422)
  const waiting=await work(root,other.id,9424)
  await pass(root.post(`/api/v1/workspaces/ws_main/people/${activator.id}/account`,{role:'member'}))
  await pass(root.post(revokedRule.path+'/jobs/process',{}))
  const refused=(await pass(root.get(revokedRule.path))).jobs.find(j=>j.task_id===waiting.id)
  assert.equal((await root.post(revokedRule.path+`/jobs/${refused.id}/schedule-approve`,{token:'synthetic-pegboard-9425'})).status,409)
  assert.equal(refused.status,'pending');assert.equal(refused.operation_id,null);assert.deepEqual(dates(await read(root,waiting.id)),['2026-06-29','2026-07-01'])
 })
}
