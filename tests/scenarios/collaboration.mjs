import assert from 'node:assert/strict'
const address=n=>['synthetic-pegboard-'+n,'example.test'].join(String.fromCharCode(64))
const ok=async(promise,status=200)=>{const r=await promise;assert.equal(r.status,status,JSON.stringify(r.body));return r.body}
export function registerCollaborationTests({test,context}) {
 test('collaborates on durable text with attributed revisions, replay-safe reactions and explicit stale-edit refusals',async()=>{
  const w=context(),root=w.owner,peer=await w.person(address(1010),'Text colleague')
  const p=await ok(root.post('/api/v1/projects',{name:'Native collaboration'}))
  await ok(root.post('/api/v1/grants',{objectType:'project',objectId:p.id,granteeId:peer.id,level:'editor'}))
  const t=await ok(root.post('/api/v1/tasks',{projectId:p.id,title:'Shared text',description:'Original **description**',ownerId:peer.id}))
  const url='/api/v1/tasks/'+t.id
  let task=await ok(root.get(url));assert.equal(task.descriptionVersion,1)
  await ok(peer.patch(url,{description:'Updated **description**',descriptionVersion:1}))
  await ok(root.patch(url,{description:'Stale text must survive locally',descriptionVersion:1}),409)
  task=await ok(root.get(url));assert.deepEqual(task.descriptionVersions.map(v=>v.text),['Original **description**','Updated **description**']);assert.equal(task.descriptionVersions[1].actor,'Text colleague')
  assert.ok(task.history.some(h=>h.actor==='Text colleague'&&h.detail.description?.from==='Original **description**'&&h.detail.description?.to==='Updated **description**'&&h.at>0))
  const commentInput={body:'First **comment**',mentionId:peer.id,key:'synthetic-pegboard-1014'}
  const c=await ok(root.post(url+'/comments',commentInput))
  assert.equal((await ok(root.post(url+'/comments',commentInput))).id,c.id)
  assert.equal((await ok(root.get(url))).comments.length,1)
  await ok(root.post(url+'/comments',{...commentInput,body:'Changed captured intent'}),409)
  let comment=(await ok(root.get(url))).comments.find(cmt=>cmt.id===c.id)
  assert.equal(comment.body,'@Text colleague First **comment**')
  const createdAt=comment.at
  await ok(root.post(url+'/comments/'+c.id+'/edit',{version:1,body:'Edited *comment*'}))
  await ok(root.post(url+'/comments/'+c.id+'/edit',{version:1,body:'Outdated comment'}),409)
  await ok(peer.post(url+'/comments/'+c.id+'/edit',{version:2,body:'Another person overwrites'}),403)
  const reaction={reaction:'thanks',active:true,key:'synthetic-pegboard-1011'}
  await ok(peer.post(url+'/comments/'+c.id+'/reactions',reaction));await ok(peer.post(url+'/comments/'+c.id+'/reactions',reaction))
  await ok(peer.post(url+'/comments/'+c.id+'/reactions',{...reaction,active:false,key:'synthetic-pegboard-1012'}))
  await ok(peer.post(url+'/comments/'+c.id+'/reactions',reaction))
  comment=(await ok(root.get(url))).comments.find(cmt=>cmt.id===c.id)
  assert.equal(comment.reactions.find(r=>r.reaction==='thanks').count,0,'replaying an old add never restores a removed reaction')
  assert.deepEqual(comment.versions.map(v=>v.body),['@Text colleague First **comment**','Edited *comment*']);assert.equal(comment.versions[1].actor,'Wes Holloway');assert.equal(comment.at,createdAt);assert.ok(comment.versions[1].at>=createdAt)
  const concurrent=await Promise.all([root.patch(url,{description:'Concurrent writer one',descriptionVersion:2}),peer.patch(url,{description:'Concurrent writer two',descriptionVersion:2})])
  assert.deepEqual(concurrent.map(r=>r.status).sort(),[200,409])
  assert.equal((await ok(root.get(url))).descriptionVersions.length,3)
  await ok(root.post(url+'/comments/'+c.id+'/delete',{version:2}))
  comment=(await ok(root.get(url))).comments.find(cmt=>cmt.id===c.id);assert.equal(comment.deleted,true);assert.equal(comment.body,'');assert.equal(comment.versions[2].deleted,true)
  await ok(peer.post(url+'/comments/'+c.id+'/reactions',{...reaction,key:'synthetic-pegboard-1013'}),409)
  const brief='/api/v1/projects/'+p.id+'/brief'
  await ok(root.post(brief,{version:0,text:'# First brief\n**Agreed plan**'}))
  await ok(peer.post(brief,{version:1,text:'# Second brief\n*Colleague revision*'}))
  await ok(root.post(brief,{version:1,text:'Disconnected draft'}),409)
  await w.restart()
  const versions=(await ok(root.get(brief))).versions
  assert.deepEqual(versions.map(v=>v.text),['# Second brief\n*Colleague revision*','# First brief\n**Agreed plan**']);assert.equal(versions[0].actor,'Text colleague');assert.ok(versions[0].createdAt>=versions[1].createdAt)
  assert.equal((await ok(root.get(url))).comments[0].versions.length,3)
 })
 test('filters collaboration at every current scope and refuses revoked readers and erased capture replay',async()=>{
  const w=context(),root=w.owner,guest=await w.person(address(1020),'Scoped guest','guest'),outsider=await w.person(address(1021),'Hidden colleague')
  const p=await ok(root.post('/api/v1/projects',{name:'Shared collaboration'})),hidden=await ok(root.post('/api/v1/projects',{name:'Hidden collaboration'}))
  const grant=await ok(root.post('/api/v1/grants',{objectType:'project',objectId:p.id,granteeId:guest.id,level:'commenter'}))
  const t=await ok(root.post('/api/v1/tasks',{projectId:p.id,title:'Permitted text',ownerId:root.id,description:'Shared **description**'})),url='/api/v1/tasks/'+t.id
  await ok(root.post(url+'/projects',{projectId:hidden.id}))
  await ok(root.post(url+'/comments',{body:'Public discussion'}))
  const secret=await ok(root.post(url+'/comments',{body:'Restricted internal body',internalOnly:true}))
  await ok(root.post(url+'/comments/'+secret.id+'/edit',{version:1,body:'Restricted revision body'}))
  await ok(root.post(url+'/comments/'+secret.id+'/reactions',{reaction:'thanks',active:true,key:'synthetic-pegboard-1022'}))
  const privateTask=await ok(root.post('/api/v1/tasks',{projectId:hidden.id,title:'Hidden task title',description:'Hidden task text'}))
  await ok(root.post('/api/v1/projects/'+p.id+'/brief',{version:0,text:'Permitted brief'}))
  await ok(root.post('/api/v1/projects/'+hidden.id+'/brief',{version:0,text:'Restricted brief'}))
  const visible=await ok(guest.get(url)),serialized=JSON.stringify(visible)
  for(const text of ['Restricted internal body','Restricted revision body','Hidden collaboration',outsider.id,'Hidden colleague'])assert.ok(!serialized.includes(text),text)
  assert.deepEqual(visible.comments.map(c=>c.body),['Public discussion'])
  await ok(guest.post(url+'/comments/'+secret.id+'/reactions',{reaction:'like',active:true,key:'synthetic-pegboard-1023'}),404)
  await ok(guest.post(url+'/comments',{body:'Forbidden mention',mentionId:outsider.id}),400)
  await ok(guest.get('/api/v1/tasks/'+privateTask.id),404)
  await ok(guest.get('/api/v1/projects/'+hidden.id+'/brief'),404)
  const exported=await ok(guest.get('/api/v1/projects/'+p.id+'/export?format=json'))
  assert.deepEqual(exported.tasks.map(row=>row.id),[t.id]);assert.ok(!JSON.stringify(exported).includes('Restricted'))
  const guestComment=await ok(guest.post(url+'/comments',{body:'Guest contribution'}))
  await ok(root.post('/api/v1/grants/'+grant.id+'/revoke',{}))
  for(const path of [url,'/api/v1/projects/'+p.id+'/brief','/api/v1/projects/'+p.id+'/export?format=json'])await ok(guest.get(path),404)
  await ok(guest.post(url+'/comments',{body:'Old session write'}),404)
  await ok(guest.post(url+'/comments/'+guestComment.id+'/edit',{version:1,body:'Revoked author edit'}),404)
  const viewer=await ok(root.post('/api/v1/grants',{objectType:'project',objectId:p.id,granteeId:guest.id,level:'viewer'}))
  const before=JSON.stringify((await ok(root.get(url))).comments)
  await ok(guest.post(url+'/comments/'+guestComment.id+'/reactions',{reaction:'like',active:true,key:'synthetic-pegboard-1024'}),403)
  assert.equal(JSON.stringify((await ok(root.get(url))).comments),before)
  await ok(root.post('/api/v1/grants/'+viewer.id+'/revoke',{}))
  // Comment authority belongs to its project, even when the task has another writable home.
  const scoped=await w.person(address(1025),'Project scoped commenter')
  const authorGrant=await ok(root.post('/api/v1/grants',{objectType:'project',objectId:p.id,granteeId:scoped.id,level:'commenter'}))
  const scopedComment=await ok(scoped.post(url+'/comments',{body:'Original project discussion'}))
  const priorReaction={reaction:'thanks',active:true,key:'synthetic-pegboard-1026'}
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/reactions',priorReaction))
  await ok(root.post('/api/v1/grants/'+authorGrant.id+'/revoke',{}))
  const readGrant=await ok(root.post('/api/v1/grants',{objectType:'project',objectId:p.id,granteeId:scoped.id,level:'viewer'}))
  await ok(root.post('/api/v1/grants',{objectType:'project',objectId:hidden.id,granteeId:scoped.id,level:'commenter'}))
  assert.ok((await ok(scoped.get(url))).comments.some(c=>c.id===scopedComment.id),'the viewer may still read the original project discussion')
  const unchanged=await ok(root.get(url))
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/edit',{version:1,body:'Cross project overwrite'}),403)
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/delete',{version:1}),403)
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/reactions',{reaction:'like',active:true,key:'synthetic-pegboard-1027'}),403)
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/reactions',{reaction:'thanks',active:false,key:'synthetic-pegboard-1028'}),403)
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/reactions',priorReaction),403)
  const afterRefusals=await ok(root.get(url))
  assert.deepEqual(afterRefusals.comments,unchanged.comments,'refused writes preserve bodies, revisions and reactions')
  assert.deepEqual(afterRefusals.history,unchanged.history,'refused writes create no history')
  const writableComment=await ok(scoped.post(url+'/comments',{body:'Other project discussion'}))
  await ok(scoped.post(url+'/comments/'+writableComment.id+'/edit',{version:1,body:'Permitted project revision'}))
  await ok(scoped.post(url+'/comments/'+writableComment.id+'/reactions',{reaction:'like',active:true,key:'synthetic-pegboard-1029'}))
  const writable=(await ok(root.get(url))).comments.find(c=>c.id===writableComment.id)
  assert.equal(writable.body,'Permitted project revision');assert.equal(writable.version,2)
  assert.equal(writable.reactions.find(r=>r.reaction==='like').count,1)
  await ok(scoped.post(url+'/comments/'+writableComment.id+'/delete',{version:2}))
  assert.equal((await ok(root.get(url))).comments.find(c=>c.id===writableComment.id).deleted,true)
  await ok(root.post('/api/v1/grants/'+readGrant.id+'/revoke',{}))
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/edit',{version:1,body:'Hidden project overwrite'}),404)
  await ok(scoped.post(url+'/comments/'+scopedComment.id+'/reactions',priorReaction),404)
  const erased=await ok(root.post('/api/v1/data/erasure-preview',{type:'task',id:t.id}))
  await ok(root.post('/api/v1/data/erase',{type:'task',id:t.id,token:erased.token,confirm:true}))
  await ok(root.get(url),404)
  await ok(root.post(url+'/comments/'+secret.id+'/reactions',{reaction:'thanks',active:true,key:'synthetic-pegboard-1022'}),404)
  await ok(root.post(url+'/comments/'+secret.id+'/edit',{version:2,body:'Captured replay'}),404)
  const rows=JSON.parse(await w.sql("SELECT (SELECT COUNT(*) FROM peg_description_versions WHERE task_id='"+t.id+"')+(SELECT COUNT(*) FROM peg_comment_versions WHERE comment_id='"+secret.id+"')+(SELECT COUNT(*) FROM peg_comment_reactions WHERE comment_id='"+secret.id+"') n"))
  assert.equal(rows[0].results[0].n,0,'reviewed erasure removes retained revision and reaction bytes')
 })
}
