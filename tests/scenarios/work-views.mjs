import assert from 'node:assert/strict'

const modes = ['list', 'board', 'table', 'calendar', 'timeline', 'workload']
const pass = async (request, status = 200) => { const response = await request; assert.equal(response.status, status, JSON.stringify(response.body)); return response.body }
const invite = (w, number, name, role = 'member') => w.person([`synthetic-pegboard-${number}`, 'example.com'].join('@'), name, role)
const grant = (root, project, person, level = 'editor', scope = 'full') => pass(root.post('/api/v1/grants', {objectType:'project',objectId:project.id,granteeId:person.id,level,scope}))
const read = (client, project, mode = 'table', view) => pass(client.get(`/api/v1/projects/${project.id}/work-view?mode=${mode}${view ? '&view='+view.id : ''}`))
const presets = (client, project) => pass(client.get(`/api/v1/projects/${project.id}/work-views`))
const create = (client, project, input) => pass(client.post(`/api/v1/projects/${project.id}/work-views`, input))
const task = (client, id) => pass(client.get(`/api/v1/tasks/${id}`))
const values = rows => rows.map(row => ({id:row.id,title:row.title,status:row.status,owner:row.owner,dueDate:row.dueDate,startDate:row.startDate,estimate:row.estimate,section:row.section,fields:row.fields})).sort((a,b)=>a.id.localeCompare(b.id))

export function registerWorkViewTests({test, context}) {
 test('keeps six work views on one dated graph and restores named configuration and defaults after restart and sign-in', async () => {
  const {w} = context(), root = w.owner, editor = await invite(w,3001,'View editor')
  const project = await pass(root.post('/api/v1/projects',{name:'July production views'}))
  await grant(root,project,editor)
  const section = await pass(root.post(`/api/v1/projects/${project.id}/sections`,{name:'Production',mapsTo:'doing'}))
  const field = await pass(root.post(`/api/v1/projects/${project.id}/fields`,{key:'view_cost',label:'Production cost',type:'number'}))
  const date = await pass(root.post('/api/v1/tasks',{projectId:project.id,title:'Date-only delivery',ownerId:editor.id,startDate:'2026-07-06',dueDate:'2026-07-07',estimateHours:4}))
  const timed = await pass(root.post('/api/v1/tasks',{projectId:project.id,title:'Timed review',ownerId:editor.id,startDate:'2026-07-08T13:00:00.000Z',dueDate:'2026-07-08T14:00:00.000Z',estimateHours:1}))
  const completed = await pass(root.post('/api/v1/tasks',{projectId:project.id,title:'Completed preparation',status:'done',ownerId:root.id,dueDate:'2026-07-03'}))
  await pass(root.post(`/api/v1/tasks/${date.id}/fields`,{projectId:project.id,values:{view_cost:125}}))
  await pass(editor.post(`/api/v1/tasks/${date.id}/section`,{projectId:project.id,sectionId:section.id}))
  const first = await read(editor,project)
  assert.deepEqual(first.rows.map(row=>row.id).sort(),[date.id,timed.id,completed.id].sort())
  assert.equal(first.rows.find(row=>row.id===date.id).dueDate,'2026-07-07')
  assert.equal(first.rows.find(row=>row.id===timed.id).dueDate,'2026-07-08T14:00:00.000Z')
  assert.equal(first.rows.find(row=>row.id===date.id).status,(await task(root,date.id)).status)
  assert.equal(first.rows.find(row=>row.id===date.id).section.id,section.id)
  assert.equal(first.rows.find(row=>row.id===date.id).estimate,4)
  assert.equal(first.rows.find(row=>row.id===date.id).owner.id,editor.id)
  assert.equal(first.rows.find(row=>row.id===date.id).fields.find(row=>row.id===field.id).value,125)
  for (const id of [date.id,timed.id,completed.id]) {
   const native = await task(root,id), row = first.rows.find(value=>value.id===id)
   for (const key of ['title','status','dueDate','startDate']) assert.equal(row[key],native[key],key)
  }
  for (const mode of modes) assert.deepEqual(values((await read(editor,project,mode)).rows),values(first.rows),mode)
  const input = {name:'My July production',mode:'table',filters:{status:['todo','doing'],ownerIds:[editor.id],dueFrom:'2026-07-06',dueTo:'2026-07-10'},groupBy:'status',sort:[{column:'dueDate',direction:'desc'}],columns:['title','status','owner','dueDate',`field:${field.id}`],shared:true}
  const saved = await create(editor,project,input)
  let list = await presets(editor,project)
  await pass(editor.post(`/api/v1/projects/${project.id}/work-view-defaults`,{revision:list.defaultsRevision,scope:'personal',viewId:saved.id}))
  await pass(editor.post(`/api/v1/projects/${project.id}/work-view-defaults`,{revision:list.defaultsRevision,scope:'personal',viewId:saved.id}),409)
  list = await presets(root,project)
  await pass(root.post(`/api/v1/projects/${project.id}/work-view-defaults`,{revision:list.defaultsRevision,scope:'team',viewId:saved.id}))
  const filtered = await read(editor,project,'table',saved)
  assert.deepEqual(filtered.rows.map(row=>row.id),[timed.id,date.id])
  for (const key of ['filters','groupBy','sort','columns']) assert.deepEqual(filtered.config[key],input[key],key)
  assert.deepEqual((await read(root,project)).config,{...filtered.config,canEdit:false},'the team default is consumed without configuration edit authority')
  const beforeEdit = (await read(editor,project)).rows.find(row=>row.id===date.id)
  await pass(editor.post(`/api/v1/work-view-tasks/${date.id}/edit`,{projectId:project.id,revision:beforeEdit.revision,title:'Reviewed delivery'}))
  await pass(editor.post(`/api/v1/work-view-tasks/${date.id}/edit`,{projectId:project.id,revision:beforeEdit.revision,title:'Stale draft'}),409)
  assert.equal((await task(root,date.id)).title,'Reviewed delivery')
  const moves = [{taskId:date.id,due:'2026-07-09'}], plan = await pass(editor.post('/api/v1/schedule/preview',{moves}))
  assert.equal((await task(root,date.id)).dueDate,'2026-07-07','preview does not edit the graph')
  await pass(editor.post('/api/v1/schedule/apply',{moves,revision:plan.stamp}))
  await pass(editor.post('/api/v1/schedule/apply',{moves,revision:plan.stamp}),409)
  for (const mode of modes) assert.equal((await read(editor,project,mode,saved)).rows.find(row=>row.id===date.id).dueDate,'2026-07-09',mode)
  assert.equal((await task(root,timed.id)).dueDate,'2026-07-08T14:00:00.000Z')
  await w.restart()
  const fresh = await w.signIn(editor.email,editor.name,editor.id)
  list = await presets(fresh,project)
  assert.equal(list.personalDefaultId,saved.id)
  assert.equal(list.teamDefaultId,saved.id)
  const restored = await read(fresh,project,'table',saved)
  assert.deepEqual(restored.config,filtered.config)
  assert.deepEqual((await read(fresh,project)).config,filtered.config,'the native new session consumes its personal default')
  assert.deepEqual(restored.rows.map(row=>row.id),[date.id,timed.id])
  assert.equal((await task(root,date.id)).history.filter(row=>row.kind==='created').length,1)
 })

 test('shares only permitted work and columns and fences stale configuration, defaults and revoked authority', async () => {
  const {w} = context(), root = w.owner
  const author = await invite(w,3002,'Shared view author'), guest = await invite(w,3003,'Limited view guest','guest'), outsider = await invite(w,3004,'View outsider')
  const project = await pass(root.post('/api/v1/projects',{name:'Client view project'}))
  const authorGrant = await grant(root,project,author), guestGrant = await grant(root,project,guest,'viewer','full')
  const publicField = await pass(root.post(`/api/v1/projects/${project.id}/fields`,{key:'client_units',label:'Client units',type:'number'}))
  const hiddenField = await pass(root.post(`/api/v1/projects/${project.id}/fields`,{key:'private_margin',label:'Private margin',type:'number',visibility:'internal'}))
  const visible = await pass(root.post('/api/v1/tasks',{projectId:project.id,title:'Assigned client delivery',ownerId:guest.id,dueDate:'2026-07-07'}))
  const hidden = await pass(root.post('/api/v1/tasks',{projectId:project.id,title:'Unassigned internal delivery',ownerId:root.id,dueDate:'2026-07-07',internalOnly:true}))
  await pass(root.post(`/api/v1/tasks/${visible.id}/fields`,{projectId:project.id,values:{client_units:7,private_margin:913}}))
  const input = {name:'Shared client plan',mode:'table',filters:{status:[],ownerIds:[],dueFrom:null,dueTo:null},groupBy:`field:${hiddenField.id}`,sort:[{column:`field:${hiddenField.id}`,direction:'desc'}],columns:['title','dueDate',`field:${publicField.id}`,`field:${hiddenField.id}`],shared:true}
  const saved = await create(author,project,input), shown = await read(guest,project,'table',saved)
  const authoredDefaults=await presets(author,project)
  await pass(author.post(`/api/v1/projects/${project.id}/work-view-defaults`,{revision:authoredDefaults.defaultsRevision,scope:'personal',viewId:saved.id}))
  assert.deepEqual(shown.rows.map(row=>row.id),[visible.id])
  assert.deepEqual(shown.config.columns,['title','dueDate',`field:${publicField.id}`])
  assert.equal(shown.config.groupBy,null)
  assert.deepEqual(shown.config.sort,[])
  assert.equal(shown.rows[0].fields.find(row=>row.id===publicField.id).value,7)
  assert.ok(shown.rows[0].fields.every(row=>row.id!==hiddenField.id&&row.value!==913))
  await pass(guest.post(`/api/v1/work-view-tasks/${visible.id}/edit`,{projectId:project.id,revision:shown.rows[0].revision,title:'Viewer overwrite'}),403)
  assert.equal((await task(root,visible.id)).title,'Assigned client delivery')
  const payload = JSON.stringify(shown)
  for (const secret of [hidden.id,hiddenField.id,'Private margin','private_margin','Unassigned internal delivery']) assert.ok(!payload.includes(secret),secret)
  assert.equal((await outsider.get(`/api/v1/projects/${project.id}/work-view?view=${saved.id}`)).status,404)
  await pass(author.post(`/api/v1/projects/${project.id}/work-views`,{...input,filters:{field:hiddenField.id,value:913}}),400)
  const defaults = await presets(guest,project)
  await pass(guest.post(`/api/v1/projects/${project.id}/work-view-defaults`,{revision:defaults.defaultsRevision,scope:'team',viewId:saved.id}),403)
  const updated = await pass(author.post(`/api/v1/work-views/${saved.id}`,{...input,name:'Reviewed client plan',revision:saved.revision}))
  await pass(author.post(`/api/v1/work-views/${saved.id}`,{...input,name:'Stale client plan',revision:saved.revision}),409)
  assert.equal((await presets(author,project)).views.find(row=>row.id===saved.id).name,'Reviewed client plan')
  await pass(root.delete(`/api/v1/grants/${authorGrant.id}`))
  const refused = await author.post(`/api/v1/work-views/${saved.id}`,{...input,name:'Revoked author edit',revision:updated.revision})
  assert.ok([403,404].includes(refused.status))
  assert.equal((await guest.get(`/api/v1/projects/${project.id}/work-view?view=${saved.id}`)).status,404,'shared configuration requires its author to retain access')
  assert.equal((await task(root,visible.id)).dueDate,'2026-07-07')
  await pass(root.delete(`/api/v1/grants/${guestGrant.id}`))
  assert.equal((await guest.get(`/api/v1/projects/${project.id}/work-view?view=${saved.id}`)).status,404)
  assert.equal((await guest.get(`/api/v1/projects/${project.id}/work-views`)).status,404)
  assert.equal((await guest.get(`/api/v1/tasks/${visible.id}`)).status,404)
  await pass(root.post(`/api/v1/workspaces/ws_main/people/${author.id}/account`,{status:'inactive'}))
  const erasure=await pass(root.post('/api/v1/data/erasure-preview',{type:'person',id:author.id}))
  assert.deepEqual(erasure.blockers,[])
  assert.equal(erasure.counts.peg_work_views,1,'the exact person review includes the authored configuration')
  assert.equal(erasure.counts.peg_work_view_defaults,1,'the exact person review includes personal default custody')
  const erased=await pass(root.post('/api/v1/data/erase',{type:'person',id:author.id,token:erasure.token,confirm:true}))
  assert.equal(erased.counts.peg_work_views,1)
  assert.equal((await author.post(`/api/v1/work-views/${saved.id}`,{...input,revision:updated.revision})).status,401)
  assert.ok(!(await presets(root,project)).views.some(view=>view.id===saved.id))
  assert.equal((await task(root,visible.id)).title,'Assigned client delivery','erasing a configuration owner changes no shared task')

 })
}
