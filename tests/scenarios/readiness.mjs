import assert from 'node:assert/strict'
import { proofDocument } from '../support/worker.mjs'

const pass = async (request, status = 200) => { const response = await request; assert.equal(response.status, status, JSON.stringify(response.body)); return response.body }
const task = (client, id) => pass(client.get(`/api/v1/tasks/${id}`))
const patch = (client, id, input) => pass(client.patch(`/api/v1/tasks/${id}`, input))
const inbox = client => pass(client.get('/api/v1/notices/readiness'))
const preferences = (client, input) => pass(client.post('/api/v1/notices/readiness/preferences', input))
const noticesFor = (result, id) => result.notices.filter(notice => notice.taskId === id)
const link = (root, predecessor, successor, type = 'fs') => pass(root.post('/api/v1/dependencies', { predecessor, successor, type }))
const grant = (root, projectId, person, extra = {}) => pass(root.post('/api/v1/grants', { objectType: 'project', objectId: projectId, granteeId: person.id, level: 'editor', ...extra }))
const make = async (root, projectId, title, extra = {}) => ({...await pass(root.post('/api/v1/tasks', { projectId, title, startDate: '2026-11-02', dueDate: '2026-11-03', ...extra })),title})

async function graph(root, assignee, name) {
  const project = await pass(root.post('/api/v1/projects', { name }))
  await grant(root, project.id, assignee)
  const first = await make(root, project.id, `${name} copy`), last = await make(root, project.id, `${name} review`)
  const waiting = await make(root, project.id, `${name} release`, { ownerId: assignee.id, startDate: '2026-11-04', dueDate: '2026-11-05' })
  const edges = await Promise.all([link(root, first.id, waiting.id), link(root, last.id, waiting.id, 'ff')])
  const schedule = await pass(root.get(`/api/v1/projects/${project.id}/schedule`))
  assert.ok(schedule.tasks.some(row => row.id === waiting.id), 'readiness uses the native schedule graph')
  return { project, first, last, waiting, edges }
}

// Parent supplies existing authenticated native clients and owns the Worker lifecycle.
export function registerReadinessTests({ test, api }) {
  test('notifies the current assignee once after two blockers including concurrent and replayed completion on the schedule graph', async () => {
    const { root, peer } = api(), { project, first, last, waiting } = await graph(root, peer, 'synthetic-pegboard-readiness-101')
    await preferences(peer, { enabled: true, muted: false, inboxEnabled: true, dndUntil: null, digestUntil: null })
    const file = await pass(root.post(`/api/v1/tasks/${waiting.id}/attachments?projectId=${project.id}&name=synthetic-pegboard-readiness-103.pdf`, proofDocument('synthetic-pegboard-readiness-103'), { 'content-type': 'application/pdf' }))
    const proof = await pass(root.post(`/api/v1/tasks/${waiting.id}/proofs`, { attachmentId: file.id }))
    const proofBefore = await pass(root.get(`/api/v1/proofs/${proof.id}`))
    const before = await task(root, waiting.id), baseline = await pass(root.post(`/api/v1/projects/${project.id}/baselines`, { name: 'synthetic-pegboard-readiness-102' }))
    await patch(root, first.id, { status: 'done' })
    assert.deepEqual(noticesFor(await inbox(peer), waiting.id), [], 'one remaining blocker prevents readiness')
    await patch(root, last.id, { status: 'done' })
    const [initial, replay] = await Promise.all([inbox(peer), inbox(peer)])
    assert.equal(noticesFor(initial, waiting.id).length, 1)
    assert.deepEqual(noticesFor(initial, waiting.id), noticesFor(replay, waiting.id), 'concurrent dispatch deduplicates')
    await Promise.all([patch(root, first.id, { status: 'done' }), patch(root, last.id, { status: 'done' })])
    assert.deepEqual(noticesFor(await inbox(peer), waiting.id), noticesFor(initial, waiting.id), 'replayed completions retain the original notice')
    const notice = noticesFor(initial, waiting.id)[0]
    assert.equal((await pass(peer.get(notice.href))).includes(waiting.title), true, 'notice opens the native authorized task')
    const visible = await pass(peer.get('/app/inbox'))
    assert.ok(visible.includes(waiting.title) && visible.includes(notice.href), 'a native rendered Inbox card is visible delivery')
    await Promise.all([patch(root, first.id, { status: 'todo' }), patch(root, last.id, { status: 'todo' })])
    assert.deepEqual(noticesFor(await inbox(peer), waiting.id), [])
    await Promise.all([patch(root, last.id, { status: 'done' }), patch(root, first.id, { status: 'done' })])
    const fresh = noticesFor(await inbox(peer), waiting.id)
    assert.equal(fresh.length, 1); assert.notEqual(fresh[0].id, notice.id, 'a genuine later transition has its own identity')
    assert.deepEqual(noticesFor(await inbox(root), waiting.id), [], 'assignee audience excludes the workspace owner')
    const after = await task(root, waiting.id)
    for (const key of ['status', 'startDate', 'dueDate', 'completedAt', 'history']) assert.deepEqual(after[key], before[key], key)
    assert.deepEqual(await pass(root.get(`/api/v1/proofs/${proof.id}`)), proofBefore, 'notice delivery cannot change proof versions or decisions')
    const retained = await pass(root.get(`/api/v1/projects/${project.id}/schedule?baseline=${baseline.id}`))
    const dates = retained.tasks.find(row => row.id === waiting.id)
    assert.equal(dates.start, before.startDate); assert.equal(dates.due, before.dueDate)
    assert.equal(dates.baseline.start, before.startDate); assert.equal(dates.baseline.due, before.dueDate)
  })

  test('reroutes queued readiness to the current assignee and honors mute, quiet hours, digest and revoked access', async () => {
    const { root, peer, worker } = api(), { project, first, last, waiting } = await graph(root, peer, 'synthetic-pegboard-readiness-201')
    const outsider = await worker.person('synthetic-pegboard-readiness-202@example.com', 'Readiness recipient')
    const share = await grant(root, project.id, outsider)
    await preferences(peer, { enabled: true, muted: false, inboxEnabled: true, dndUntil: null, digestUntil: null })
    await Promise.all([patch(root, first.id, { status: 'done' }), patch(root, last.id, { status: 'done' })])
    await patch(root, waiting.id, { ownerId: outsider.id })
    assert.deepEqual(noticesFor(await inbox(peer), waiting.id), [], 'the queued audience follows reassignment')
    assert.equal(noticesFor(await inbox(outsider), waiting.id).length, 1)
    await patch(root, first.id, { status: 'todo' })
    await preferences(outsider, { muted: true })
    await patch(root, first.id, { status: 'done' })
    await preferences(outsider, { muted: false })
    assert.deepEqual(noticesFor(await inbox(outsider), waiting.id), [], 'unmuting cannot resurrect a suppressed transition')
    await patch(root, first.id, { status: 'todo' })
    const until = Date.now() + 3600000
    await preferences(outsider, { dndUntil: until })
    await patch(root, first.id, { status: 'done' })
    const quiet = await inbox(outsider)
    assert.deepEqual(noticesFor(quiet, waiting.id), [])
    assert.ok(quiet.deferred.some(row => row.taskId === waiting.id && row.reason === 'quiet_hours' && row.nextEligibleAt === until))
    await preferences(outsider, { dndUntil: null, digestUntil: until })
    assert.ok((await inbox(outsider)).deferred.some(row => row.taskId === waiting.id && row.reason === 'digest'))
    await preferences(outsider, { digestUntil: null })
    assert.equal(noticesFor(await inbox(outsider), waiting.id).length, 1, 'clearing the hold releases exactly the retained transition')
    await patch(root, first.id, { status: 'todo' })
    await patch(root, first.id, { status: 'done' })
    await pass(root.delete(`/api/v1/grants/${share.id}`))
    const revoked = await inbox(outsider)
    assert.deepEqual(noticesFor(revoked, waiting.id), []); assert.ok(!JSON.stringify(revoked).includes(waiting.title))
    await grant(root, project.id, outsider)
    assert.deepEqual(noticesFor(await inbox(outsider), waiting.id), [], 'revocation consumes the queued notice')
    await patch(root, first.id, { status: 'todo' })
    await patch(root, first.id, { status: 'done' })
    assert.equal(noticesFor(await inbox(outsider), waiting.id).length, 1)
  })

  test('keeps a scoped guest and hidden predecessors private and cancels obsolete readiness before a fresh graph transition', async () => {
    const { root, guest } = api(), project = await pass(root.post('/api/v1/projects', { name: 'synthetic-pegboard-readiness-301' }))
    const share = await grant(root, project.id, guest, { scope: 'assignee' })
    await preferences(guest, { enabled: true, muted: false, inboxEnabled: true, dndUntil: null, digestUntil: null })
    const hidden = await make(root, project.id, 'synthetic-pegboard-readiness-hidden-302', { internalOnly: true })
    const first = await make(root, project.id, 'synthetic-pegboard-readiness-hidden-303', { internalOnly: true, kind: 'approval', ownerId: guest.id })
    const waiting = await make(root, project.id, 'synthetic-pegboard-readiness-304', { ownerId: guest.id })
    await link(root, hidden.id, waiting.id); await link(root, first.id, waiting.id, 'ss')
    const schedule = await pass(root.get(`/api/v1/projects/${project.id}/schedule`))
    assert.ok(schedule.tasks.some(row => row.id === waiting.id))
    const before = await task(root, waiting.id), decision = await pass(root.get(`/api/v1/tasks/${first.id}/decision-preview`))
    await pass(root.post(`/api/v1/tasks/${first.id}/decision`, { revision: decision.token, action: 'approve', reason: 'synthetic-pegboard-readiness-305' }))
    assert.deepEqual(noticesFor(await inbox(guest), waiting.id), [])
    await patch(root, hidden.id, { status: 'done' })
    await patch(root, hidden.id, { status: 'todo' })
    assert.deepEqual(noticesFor(await inbox(guest), waiting.id), [], 'reopening cancels the unsent notice')
    await patch(root, hidden.id, { status: 'done' })
    const added = await make(root, project.id, 'synthetic-pegboard-readiness-hidden-306', { internalOnly: true })
    const addedLink = await link(root, added.id, waiting.id)
    assert.deepEqual(noticesFor(await inbox(guest), waiting.id), [], 'a new blocker cancels the unsent notice')
    await pass(root.delete(`/api/v1/dependencies/${addedLink.id}`))
    const beforeDispatch = await task(root, waiting.id)
    const ready = await inbox(guest), notice = noticesFor(ready, waiting.id)
    assert.equal(notice.length, 1, 'removing the last new blocker creates one fresh transition')
    for (const predecessor of [hidden, first, added]) {
      assert.ok(!JSON.stringify(ready).includes(predecessor.id)); assert.ok(!JSON.stringify(ready).includes(predecessor.title))
      await pass(guest.get(`/api/v1/tasks/${predecessor.id}`), 404)
    }
    assert.equal((await pass(guest.get(notice[0].href))).includes(waiting.title), true)
    const visibleTask=await task(guest,waiting.id)
    for(const predecessor of [hidden,first,added])assert.ok(!JSON.stringify(visibleTask).includes(predecessor.id),'native task history reveals no hidden predecessor identity')
    const after = await task(root, waiting.id)
    for (const key of ['status', 'startDate', 'dueDate', 'completedAt']) assert.deepEqual(after[key], before[key], key)
    assert.deepEqual(after.history, beforeDispatch.history, 'dispatch cannot write task history')
    assert.equal((await pass(root.get(`/api/v1/tasks/${first.id}/decision-preview`))).state, 'approved', 'notice dispatch cannot make or reopen an approval decision')
    await patch(root, hidden.id, { status: 'todo' }); await patch(root, hidden.id, { status: 'done' })
    await pass(root.delete(`/api/v1/grants/${share.id}`))
    assert.deepEqual(noticesFor(await inbox(guest), waiting.id), [])
  })
}
