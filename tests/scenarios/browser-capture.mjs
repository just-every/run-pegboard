  await ok(member.post('/auth/signout',{}),204)
  await ok(member.post(`/api/v1/captures/${personal.id}/confirm`,{proof:sessions.proof}),401)
  const inactive=capturePayload(),pending=await ok(newSession.post('/api/v1/captures',inactive.input))
