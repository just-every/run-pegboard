  await ok(newSession.get(`/api/v1/captures/${pending.id}`),401)
  await ok(root.post(`/api/v1/workspaces/ws_main/people/${member.id}/account`,{status:'active'}))
  const renewed=await w.signIn(member.email,member.name,member.id)
  await ok(renewed.post('/api/v1/captures',inactive.input),409)
  const privateTasks=await ok(renewed.get('/api/v1/my-tasks'));assert.equal(privateTasks.tasks.length,0)
  const expiring=capturePayload(),expires=await ok(renewed.post('/api/v1/captures',expiring.input))
  await w.sql(`UPDATE peg_capture_intents SET expires_at=0 WHERE id='${expires.id}'`)
  await ok(renewed.post(`/api/v1/captures/${expires.id}/confirm`,{proof:expiring.proof}),409)
  const privateCapture=capturePayload(),privateIntent=await ok(renewed.post('/api/v1/captures',privateCapture.input))
  const privateReview=await ok(renewed.post(`/api/v1/captures/${privateIntent.id}/review`,{ownerId:member.id}))
  assert.equal(privateReview.target.visibility,'Private: only you')
  const privateTask=await ok(renewed.post(`/api/v1/captures/${privateIntent.id}/confirm`,{reviewToken:privateReview.reviewToken,proof:privateCapture.proof}))
