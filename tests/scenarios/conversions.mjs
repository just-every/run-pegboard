const label=n=>`synthetic-pegboard-${n}`
const pass=async(promise,status=200)=>{const response=await promise;assert.equal(response.status,status,JSON.stringify(response.body));return response.body}
const task=(client,id)=>pass(client.get(`/api/v1/tasks/${id}`))
const project=(client,n)=>pass(client.post('/api/v1/projects',{name:label(n)}))
const work=(client,projectId,n,extra={})=>pass(client.post('/api/v1/tasks',{projectId,title:label(n),...extra}))
const grant=(root,projectId,person,level='editor')=>pass(root.post('/api/v1/grants',{objectType:'project',objectId:projectId,granteeId:person.id,level}))
const preview=(client,input)=>pass(client.post('/api/v1/conversions/preview',input))
const apply=(client,input,plan)=>pass(client.post('/api/v1/conversions/apply',{...input,token:plan.token}))
async function nativeHistory(client,ids,plan,people=[client]){
  assert.deepEqual(plan.reconciliation.manifest.tasks.map(row=>row.id).sort(),[...ids].sort())
  const entries=(await Promise.all(ids.map(id=>task(client,id)))).flatMap(row=>row.history.map(entry=>({id:entry.id,taskId:row.id,kind:entry.kind,projectId:entry.projectId,actorId:people.find(person=>person.name===entry.actor)?.id})))
  assert.ok(entries.length>=ids.length,'each native work record has independently readable history')
  assert.ok(entries.every(entry=>entry.actorId),'every history actor matches an independently signed-in person')
  assert.equal(plan.reconciliation.history,entries.length,'preview reconciles the exact native history total')
  assert.deepEqual(plan.reconciliation.manifest.history.map(row=>({id:row.id,taskId:row.taskId,kind:row.kind,projectId:row.projectId,actorId:row.actorId})).sort((a,b)=>a.id-b.id),entries.sort((a,b)=>a.id-b.id))
}
const sha=bytes=>createHash('sha256').update(bytes).digest('hex')

function conserved(before,after,addedHistory=before.tasks){
  assert.equal(after.history,before.history+addedHistory,'exact history total includes only attributed conversion events')
  for(const key of ['tasks','comments','files','proofVersions','timeEntries','timeSeconds','aliases','dependencies','fields','collaborators'])assert.equal(after[key],before[key],key)
  for(const key of ['tasks','comments','files','proofVersions','time','aliases','dependencies','fields','collaborators'])assert.deepEqual(after.manifest[key],before.manifest[key],key)
  for(const entry of before.manifest.history)assert.deepEqual(after.manifest.history.find(row=>row.id===entry.id),entry,'historical entry and attribution retained')
}

async function approve(root,id,n){
  const decision=await pass(root.get(`/api/v1/tasks/${id}/decision-preview`))
  await pass(root.post(`/api/v1/tasks/${id}/decision`,{revision:decision.token,action:'approve',reason:label(n)}))
  return pass(root.get(`/api/v1/tasks/${id}/decision-preview`))
}

