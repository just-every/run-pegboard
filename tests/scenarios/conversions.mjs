    const child=await pass(root.post('/api/v1/tasks',{parentId:selected.id,title:label(9204)}))
    await pass(root.post(`/api/v1/tasks/${selected.id}/comments`,{body:label(9205)}))
    const bundle=await pass(root.post('/api/v1/workflow-bundles',{name:label(9206)})),path=`/api/v1/workflow-bundles/${bundle.id}`
    for(const component of [{key:label(9207),kind:'rule',name:label(9207),priority:'urgent'},{key:label(9208),kind:'view',name:label(9208),status:'todo'}]){
      const current=await pass(root.get(path));await pass(root.post(path+'/versions',{version:current.current.version,...component}))
    }
    const adoption=await pass(root.post(path+'/preview',{projectIds:[source.id]}))
    await pass(root.post(path+'/adopt',{projectIds:[source.id],keys:[label(9207),label(9208)],revision:adoption.token}))
    const input={kind:'project_to_task',sourceId:source.id,name:label(9209),taskIds:[selected.id],retainIds:[retained.id]}
    const plan=await preview(root,input)
    assert.equal(plan.mapping.find(row=>row.taskId===selected.id).action,'subtask')
    assert.equal(plan.mapping.find(row=>row.taskId===retained.id).action,'retained_link')
    const result=await apply(root,input,plan);conserved(plan.reconciliation,result.reconciliation)
