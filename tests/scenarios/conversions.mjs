  test('promotes and demotes the same task identities and refuses cycles, disclosure, stale review and unauthorized targets',async()=>{
    const {root,peer,guest}=api(),source=await project(root,9301)
    await grant(root,source.id,peer)
    const parent=await work(root,source.id,9302),child=await pass(root.post('/api/v1/tasks',{parentId:parent.id,title:label(9303)}))
    const nested=await pass(root.post('/api/v1/tasks',{parentId:child.id,title:label(9304)}))
    await pass(peer.post(`/api/v1/tasks/${child.id}/comments`,{body:label(9305)}))
    const before=await task(root,child.id),promotion={kind:'promote',sourceId:child.id}
    const promoted=await apply(root,promotion,await preview(root,promotion)),after=await task(root,child.id)
    assert.equal(promoted.taskId,child.id);assert.equal(after.parentId,null);assert.deepEqual(after.comments,before.comments)
    for(const entry of before.history)assert.deepEqual(after.history.find(row=>row.id===entry.id),entry)
    assert.equal((await task(root,nested.id)).parentId,child.id)
    await pass(root.post('/api/v1/conversions/preview',{kind:'demote',sourceId:child.id,parentId:nested.id}),409)
    const demotion={kind:'demote',sourceId:child.id,parentId:parent.id},stale=await preview(root,demotion)
    await pass(peer.patch(`/api/v1/tasks/${child.id}`,{description:label(9306)}))
    await pass(root.post('/api/v1/conversions/apply',{...demotion,token:stale.token}),409)
    const demoted=await apply(root,demotion,await preview(root,demotion))
    assert.equal(demoted.taskId,child.id);assert.equal((await task(root,child.id)).parentId,parent.id)
    assert.equal((await task(root,nested.id)).parentId,child.id)
    const publicProject=await project(root,9307);await grant(root,publicProject.id,guest,'viewer')
    const publicParent=await work(root,publicProject.id,9308),privateTask=await work(root,source.id,9309)
    await pass(root.post('/api/v1/conversions/preview',{kind:'demote',sourceId:privateTask.id,parentId:publicParent.id}),409)
    const personal=await pass(peer.post('/api/v1/tasks',{title:label(9310)}))
    await pass(peer.post('/api/v1/conversions/preview',{kind:'demote',sourceId:personal.id,parentId:parent.id}),409)
    await pass(peer.post('/api/v1/conversions/preview',{kind:'demote',sourceId:privateTask.id,parentId:publicParent.id}),404)
    await pass(guest.get(`/api/v1/tasks/${privateTask.id}`),404)
    assert.equal((await task(root,privateTask.id)).parentId,null)
  })

  test('replays conversion once and selectively undoes structural effects without deleting later human edits or restoring sign-off',async()=>{
    const {root,peer}=api(),source=await project(root,9401)
    await grant(root,source.id,peer)
    const parent=await work(root,source.id,9402),approval=await work(root,source.id,9403,{kind:'approval',ownerId:peer.id})
    const approved=await approve(root,approval.id,9404),input={kind:'demote',sourceId:approval.id,parentId:parent.id},plan=await preview(root,input)
    const result=await apply(root,input,plan),replayed=await apply(root,input,plan)
    assert.equal(replayed.id,result.id);assert.equal(replayed.taskId,approval.id)
    const path=`/api/v1/conversions/${result.id}`,reopened=await pass(root.get(`/api/v1/tasks/${approval.id}/decision-preview`))
    assert.equal(reopened.state,'reopened');assert.deepEqual(reopened.decisions,approved.decisions)
    await pass(peer.patch(`/api/v1/tasks/${approval.id}`,{title:label(9405),description:label(9406)}))
    const comment=await pass(peer.post(`/api/v1/tasks/${approval.id}/comments`,{body:label(9407)}))
    const stale=await pass(root.post(path+'/undo/preview',{}))
    await pass(peer.patch(`/api/v1/tasks/${approval.id}`,{description:label(9408)}))
    await pass(root.post(path+'/undo',{token:stale.token}),409)
    const undo=await pass(root.post(path+'/undo/preview',{}))
    await pass(root.post(path+'/undo',{token:undo.token}))
    const after=await task(root,approval.id)
    assert.equal(after.parentId,null);assert.equal(after.title,label(9405));assert.equal(after.description,label(9408))
    assert.ok(after.comments.some(row=>row.id===comment.id&&row.body===label(9407)));assert.equal(after.status,'todo')
    const decision=await pass(root.get(`/api/v1/tasks/${approval.id}/decision-preview`))
    assert.equal(decision.state,'reopened');assert.deepEqual(decision.decisions,approved.decisions)
    const undone=await pass(root.get(path));assert.ok(undone.undoneAt)
    assert.equal(after.history.filter(row=>row.detail.conversionId===result.id&&['converted','work.converted'].includes(row.kind)).length,1)
    const undoReplay=await pass(root.post(path+'/undo',{token:undo.token}))
    assert.equal(undoReplay.undoneAt,undone.undoneAt);assert.deepEqual((await task(root,approval.id)).history,after.history)
    const first=await work(root,source.id,9409),second=await work(root,source.id,9410),child=await pass(root.post('/api/v1/tasks',{parentId:first.id,title:label(9411)}))
    const promote={kind:'promote',sourceId:child.id},conversion=await apply(root,promote,await preview(root,promote))
    const laterDemotion={kind:'demote',sourceId:child.id,parentId:second.id}
    await apply(root,laterDemotion,await preview(root,laterDemotion))
    const conflict=await pass(root.post(`/api/v1/conversions/${conversion.id}/undo/preview`,{}))
    assert.ok(conflict.conflicts.length,'later human structural change is reported')
    await pass(root.post(`/api/v1/conversions/${conversion.id}/undo`,{token:conflict.token}))
    assert.equal((await task(root,child.id)).parentId,second.id)
  })
